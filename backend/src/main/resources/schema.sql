CREATE TABLE IF NOT EXISTS admin_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS person (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  person_no VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(50) NOT NULL,
  department VARCHAR(80) NOT NULL DEFAULT '',
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  feature TEXT,
  enrolled_at TIMESTAMP NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS door (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(80) NOT NULL UNIQUE,
  location VARCHAR(120) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS access_grant (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  person_id BIGINT NOT NULL,
  door_id BIGINT NOT NULL,
  valid_from TIMESTAMP NOT NULL,
  valid_until TIMESTAMP NOT NULL,
  CONSTRAINT uq_person_door UNIQUE (person_id, door_id),
  FOREIGN KEY (person_id) REFERENCES person(id) ON DELETE CASCADE,
  FOREIGN KEY (door_id) REFERENCES door(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS access_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  person_id BIGINT NULL,
  person_name VARCHAR(50),
  person_no VARCHAR(40),
  door_id BIGINT NOT NULL,
  door_name VARCHAR(80) NOT NULL,
  allowed BOOLEAN NOT NULL,
  reason VARCHAR(60) NOT NULL,
  score DOUBLE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (person_id) REFERENCES person(id) ON DELETE SET NULL,
  FOREIGN KEY (door_id) REFERENCES door(id)
);
